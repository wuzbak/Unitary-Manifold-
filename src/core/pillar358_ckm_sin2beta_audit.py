def sin2beta_from_wolfenstein(
    rho_bar: float = RHO_BAR,
    eta_bar: float = ETA_BAR,
) -> float:
    """Compute sin(2β) from Wolfenstein ρ̄, η̄ parameters.

    From the standard unitarity triangle:
        tan(β) = η̄ / (1 − ρ̄)
        sin(2β) = 2 sin(β) cos(β)

    Parameters
    ----------
    rho_bar, eta_bar : float
        Wolfenstein ρ̄ and η̄.

    Returns
    -------
    float
        sin(2β).
    """
    beta_rad = math.atan2(eta_bar, 1.0 - rho_bar)
    return math.sin(2.0 * beta_rad)


def gamma_angle_from_wolfenstein(
    rho_bar: float = RHO_BAR,
    eta_bar: float = ETA_BAR,
) -> float:
    """Compute CKM angle γ [degrees] from Wolfenstein ρ̄, η̄.

    From the unitarity triangle:
        tan(γ) = η̄ / ρ̄
        γ = arctan(η̄ / ρ̄)

    Parameters
    ----------
    rho_bar, eta_bar : float
        Wolfenstein ρ̄ and η̄.

    Returns
    -------
    float
        γ in degrees.
    """
    gamma_rad = math.atan2(eta_bar, rho_bar)
    return math.degrees(gamma_rad)


